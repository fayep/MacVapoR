#!/bin/sh
# Builds vkfeatures' vulkan-1.dll (x86-64 Windows) into out/: see vkfeatures.c.
#   compat/vkfeatures/build.sh
# Needs llvm-mingw (LLVM_MINGW, default DXMT's toolchain) and the Vulkan headers (VULKAN_INCLUDE,
# default Homebrew's). exports.txt is Wine's vulkan-1.dll export list; the functions vkfeatures.c
# defines are left out of the generated pass-through stubs.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
LLVM_MINGW=${LLVM_MINGW:-$HOME/Source/dxmt/toolchains/llvm-mingw-20260908-ucrt-macos-universal}
VULKAN_INCLUDE=${VULKAN_INCLUDE:-/opt/homebrew/include}
out=$here/out
mkdir -p "$out"
ours="vkCreateInstance vkEnumerateDeviceExtensionProperties vkGetInstanceProcAddr vkGetDeviceProcAddr vkGetPhysicalDeviceFeatures vkGetPhysicalDeviceFeatures2 vkGetPhysicalDeviceProperties vkGetPhysicalDeviceProperties2 vkCreateDevice vkCreateGraphicsPipelines vkCmdSetLineWidth vkCreateShaderModule vkDestroyShaderModule"
python3 -I - "$here/exports.txt" "$out" $ours <<'PY'
import sys
exports = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out, ours = sys.argv[2], set(sys.argv[3:])
passed = [e for e in exports if e not in ours]
with open(out + "/stubs.S", "w") as s:
    s.write("# Generated by build.sh: pass-through jumps to the system vulkan-1.dll.\n")
    s.write("\t.data\n\t.p2align 3\n\t.globl vkf_real\nvkf_real:\n")
    for _ in passed: s.write("\t.quad 0\n")
    s.write("\t.section .rdata,\"dr\"\n")
    for i, e in enumerate(passed): s.write(f"name{i}:\n\t.asciz \"{e}\"\n")
    s.write("\t.p2align 3\n\t.globl vkf_names\nvkf_names:\n")
    for i, _ in enumerate(passed): s.write(f"\t.quad name{i}\n")
    s.write(f"\t.globl vkf_count\nvkf_count:\n\t.long {len(passed)}\n")
    s.write("\t.text\n")
    for i, e in enumerate(passed):
        s.write(f"\t.globl {e}\n\t.p2align 4\n{e}:\n\tjmp *vkf_real+{8*i}(%rip)\n")
with open(out + "/vulkan-1.def", "w") as d:
    d.write("LIBRARY vulkan-1.dll\nEXPORTS\n")
    for e in exports: d.write(f"  {e}\n")
print(f"{len(passed)} pass-through, {len(exports) - len(passed)} wrapped")
PY
"$LLVM_MINGW/bin/x86_64-w64-mingw32-clang" -O2 -Wall -Wextra -Wno-cast-function-type -shared -I"$VULKAN_INCLUDE" \
    "$here/vkfeatures.c" "$out/stubs.S" "$out/vulkan-1.def" -Wl,--no-insert-timestamp -o "$out/vulkan-1.dll"
echo "built $out/vulkan-1.dll"
